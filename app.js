/* --- Lightbox --- */
function openLightbox(items, idx = 0) {
  lbItems = items;
  lbIdx = idx;
  syncLightbox();
  const lb = document.getElementById("lightbox");
  lb.classList.add("open");
  lb.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
}

function closeLightbox() {
  const lb = document.getElementById("lightbox");
  lb.classList.remove("open");
  lb.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

function syncLightbox() {
  const item = lbItems[lbIdx];
  if (!item) return;
  document.getElementById("lbImg").src = item.src;
  document.getElementById("lbCap").textContent = item.cap || "";
  const multi = lbItems.length > 1;
  document.getElementById("lbPrev").style.display = multi ? "grid" : "none";
  document.getElementById("lbNext").style.display = multi ? "grid" : "none";
}

/* --- Adaptive Light/Dark Header Theme Based on Underlying Section --- */
function updateNavTheme() {
  const nav = document.getElementById("siteNav");
  const darkIds = ["creative", "utilities", "poster"];
  const y = window.scrollY + 34;
  let onDark = false;
  for (const id of darkIds) {
    const el = document.getElementById(id);
    if (el && y >= el.offsetTop && y < el.offsetTop + el.offsetHeight) {
      onDark = true;
      break;
    }
  }
  nav.classList.toggle("is-dark", onDark);
}

function renderAll() {
  applyI18n();
  renderHeroDock();
  updateHeroPositions();
  renderIndex();
  renderAppTabs();
  renderMonographAndFinale();
}


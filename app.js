function tr(key) {
  return (I18N[lang] && I18N[lang][key]) || key;
}

function applyI18n() {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = tr(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = tr(el.dataset.i18nHtml); });
  document.querySelectorAll(".lang-item").forEach(el => el.classList.toggle("active", el.dataset.lang === lang));
}

/* --- ACT I: 3D Spatial Theatre --- */
function initHeroStage() {
  const stage = document.getElementById("theatreStage");
  stage.innerHTML = SUITE.map((app, i) => `
    <div class="spatial-plane" data-idx="${i}">
      <img src="${app.heroShot}" alt="${app.name}" />
    </div>
  `).join("");

  stage.querySelectorAll(".spatial-plane").forEach(el => {
    el.addEventListener("click", () => {
      const idx = Number(el.dataset.idx);
      if (idx === heroIdx) {
        const app = SUITE[idx];
        openLightbox(app.tabs.map(t => ({ src: t.src, cap: `${app.name} · ${t.title[lang]}` })), 0);
      } else {
        setHero(idx, true);
      }
    });
  });

  renderHeroDock();
  updateHeroPositions();
}

function renderHeroDock() {
  const dock = document.getElementById("heroDock");
  dock.innerHTML = SUITE.map((app, i) => `
    <button type="button" class="dock-item ${i === heroIdx ? "active" : ""}" data-idx="${i}" role="tab" aria-selected="${i === heroIdx}">
      <img src="${app.icon}" alt="${app.name}" />
      <span>
        <span class="dock-n">${app.num}</span>
        <span class="dock-t">${app.short}</span>
      </span>
    </button>
  `).join("");
  dock.querySelectorAll(".dock-item").forEach(btn => {
    btn.addEventListener("click", () => setHero(Number(btn.dataset.idx), true));
  });
}

function updateHeroPositions() {
  const n = SUITE.length;
  const planes = document.querySelectorAll(".spatial-plane");
  planes.forEach((plane, i) => {
    plane.classList.remove("pos-center", "pos-left", "pos-right", "pos-far-left", "pos-far-right");
    const diff = (i - heroIdx + n) % n;
    if (diff === 0) plane.classList.add("pos-center");
    else if (diff === 1) plane.classList.add("pos-right");
    else if (diff === n - 1) plane.classList.add("pos-left");
    else if (diff <= n / 2) plane.classList.add("pos-far-right");
    else plane.classList.add("pos-far-left");
  });

  const app = SUITE[heroIdx];
  document.getElementById("heroNum").textContent = `${app.num} / 08`;
  document.getElementById("heroAppName").textContent = app.name;
  document.getElementById("heroAppLine").textContent = app.line[lang];
  document.getElementById("heroDeepLink").href = `#app-${app.id}`;

  document.querySelectorAll("#heroDock .dock-item").forEach((btn, i) => {
    btn.classList.toggle("active", i === heroIdx);
    btn.setAttribute("aria-selected", String(i === heroIdx));
  });
}

function setHero(idx, manual = false) {
  heroIdx = (idx + SUITE.length) % SUITE.length;
  updateHeroPositions();
  if (manual) startAutoCycle();
}

function startAutoCycle() {
  if (autoTimer) clearInterval(autoTimer);
  autoTimer = setInterval(() => setHero(heroIdx + 1, false), 6000);
}


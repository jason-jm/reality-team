/* --- Lightbox --- */
function openLightbox(items, startIdx = 0) {
  lightboxItems = items;
  lightboxPos = startIdx;
  updateLightbox();
  const lb = document.getElementById("lightbox");
  lb.classList.add("open");
  lb.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
}

function closeLightbox() {
  const lb = document.getElementById("lightbox");
  lb.classList.remove("open");
  lb.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
}

function updateLightbox() {
  if (!lightboxItems.length) return;
  const item = lightboxItems[lightboxPos];
  document.getElementById("lightboxImg").src = item.src;
  document.getElementById("lightboxImg").alt = item.caption;
  document.getElementById("lightboxCaption").textContent = item.caption;
  const showNav = lightboxItems.length > 1;
  document.getElementById("lightboxPrev").style.display = showNav ? "grid" : "none";
  document.getElementById("lightboxNext").style.display = showNav ? "grid" : "none";
}

/* --- Scroll Reveal (Progressive + Hash-Safe) --- */
let revealObserver = null;
function sweepVisibleReveals() {
  const vh = window.innerHeight || 900;
  document.querySelectorAll(".reveal:not(.is-visible)").forEach(el => {
    const rect = el.getBoundingClientRect();
    if (rect.top < vh + 140) {
      el.classList.add("is-visible");
    }
  });
}

function observeReveals() {
  document.documentElement.classList.add("js-reveal");
  if (revealObserver) revealObserver.disconnect();
  revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.02, rootMargin: "120px 0px 120px 0px" });

  document.querySelectorAll(".reveal").forEach(el => revealObserver.observe(el));
  requestAnimationFrame(sweepVisibleReveals);
}

